begin;

alter table public.tournament_results add column if not exists player_uid text;
alter table public.tournament_results add column if not exists reward_recipient_user_id uuid references public.profiles(id) on delete set null;
create index if not exists tournament_results_player_uid_idx on public.tournament_results(player_uid);
create index if not exists tournament_results_reward_recipient_user_idx on public.tournament_results(reward_recipient_user_id);

create table if not exists public.tournament_result_players (
  id bigint generated by default as identity primary key,
  result_id bigint not null references public.tournament_results(id) on delete cascade,
  participant_id bigint not null references public.tournament_participants(id) on delete cascade,
  player_uid text not null check (player_uid ~ '^[0-9]{5,20}$'),
  user_id uuid references public.profiles(id) on delete set null,
  position_prize numeric not null default 0,
  kills integer not null default 0 check (kills >= 0),
  kill_reward numeric not null default 0,
  total_payout numeric not null default 0,
  reward_recipient_user_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(result_id, player_uid)
);
create index if not exists tournament_result_players_uid_idx on public.tournament_result_players(player_uid);
create index if not exists tournament_result_players_result_idx on public.tournament_result_players(result_id);
alter table public.tournament_result_players enable row level security;
revoke all on table public.tournament_result_players from anon, authenticated;
revoke all on table public.tournament_results from anon, authenticated;

commit;